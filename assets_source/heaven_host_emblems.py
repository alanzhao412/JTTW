def preview():
    from PIL import Image, ImageDraw
    MANSIONS = list(EMBLEMS)
    cell, cols = 8, 7
    img = Image.new('RGB', (cols * 22 * cell, 4 * 18 * cell), (60, 60, 70))
    d = ImageDraw.Draw(img)
    for n, name in enumerate(MANSIONS):
        ox, oy = (n % cols) * 22 * cell + 2 * cell, (n // cols) * 18 * cell + 2 * cell
        for j, row in enumerate(EMBLEMS[name]):
            assert len(row) == 18, (name, j, len(row))
            for i, ch in enumerate(row):
                c = {'#': (236, 188, 70), 'o': (40, 60, 50), '*': (255, 255, 255)}.get(ch, (90, 120, 110))
                d.rectangle([ox + i * cell, oy + j * cell, ox + (i + 1) * cell - 1, oy + (j + 1) * cell - 1], fill=c)
    img.save('C:/Users/drago/AppData/Local/Temp/claude/C--Users-drago/9deb8a92-f8f3-4216-b65a-8763640de1eb/scratchpad/host_emblems_preview.png')


if __name__ == '__main__':
    preview()
