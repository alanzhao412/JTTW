    private static String legName(int i) {
        return switch (i) {
            case 0 -> "right_front_leg";
            case 1 -> "left_front_leg";
            case 2 -> "right_hind_leg";
            default -> "left_hind_leg";
        };
    }

    public static final class Model extends EntityModel<WhiteTigerEntity> {
        private final ModelPart root, head, jaw, neck, tail, tailEnd;
        private final ModelPart[] legs = new ModelPart[4];

        public Model(ModelPart root) {
            this.root = root;
            this.head = root.getChild("head");
            this.jaw = head.getChild("jaw");
            this.neck = root.getChild("neck");
            this.tail = root.getChild("tail");
            this.tailEnd = tail.getChild("tail_end");
            for (int i = 0; i < 4; i++) legs[i] = root.getChild(legName(i));
        }

        @Override
        public void setupAnim(WhiteTigerEntity e, float swing, float amount, float age, float yaw, float pitch) {
            // the head low and level, turning where it looks; the jaw working a little, as it breathes
            head.yRot = yaw * Mth.DEG_TO_RAD * 0.6f;
            head.xRot = pitch * Mth.DEG_TO_RAD * 0.5f;
            jaw.xRot = 0.75f + Mth.sin(age * 0.09f) * 0.06f; // roaring
            // a stalking gait: the legs of a side together, the forequarters rolling
            for (int i = 0; i < 4; i++) {
                boolean right = i % 2 == 0, front = i < 2;
                legs[i].xRot = Mth.cos(swing * 0.5f + (right ? 0 : Mth.PI) + (front ? 0 : 0.7f)) * 0.9f * amount;
            }
            // the tail low and long, its end flicking
            tail.yRot = Mth.sin(age * 0.07f) * 0.2f * (1 - amount * 0.6f);
            tail.xRot = -0.55f + amount * 0.25f;
            tailEnd.xRot = 0.5f + Mth.sin(age * 0.13f) * 0.15f;
        }

        @Override
        public void renderToBuffer(PoseStack pose, VertexConsumer vc, int light, int overlay, float r, float g, float b, float a) {
            root.render(pose, vc, light, overlay, r, g, b, a);
        }
    }
